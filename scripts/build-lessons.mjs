function theorySource(lesson) {
  const data = {
    qualities: lesson.qualities.map((item) => ({
      id: item.id,
      label: item.label,
      suffix: item.suffix,
      suffixBass: item.suffixBass == null ? null : item.suffixBass,
      root: item.root,
      spell: item.spell || "sharp",
      intervals: item.intervals,
      labels: item.labels,
      colorFrom: item.colorFrom,
      degrees: item.degrees,
      summary: item.summary,
      highNote: item.highNote,
      piano: item.piano,
      pianoBass: item.pianoBass == null ? null : item.pianoBass,
      bass: item.bass,
      bassLabels: item.bassLabels || ["根音", "五音"],
      walkLabel: item.walkLabel || "根—五—根",
      compares: item.compares || lesson.compare || [],
      shapes: item.shapes
    }))
  };
  return `/* Generated by scripts/build-lessons.mjs. */
(function (root, factory) {
  var api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.ChordTheory = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  var DATA = ${JSON.stringify(data)};
  var KEYS = [
    { id: "C", name: "C", pc: 0 }, { id: "Db", name: "D♭", pc: 1 }, { id: "D", name: "D", pc: 2 },
    { id: "Eb", name: "E♭", pc: 3 }, { id: "E", name: "E", pc: 4 }, { id: "F", name: "F", pc: 5 },
    { id: "Fs", name: "F♯", pc: 6 }, { id: "G", name: "G", pc: 7 }, { id: "Ab", name: "A♭", pc: 8 },
    { id: "A", name: "A", pc: 9 }, { id: "Bb", name: "B♭", pc: 10 }, { id: "B", name: "B", pc: 11 }
  ];
  var SHARP = ["C", "C♯", "D", "D♯", "E", "F", "F♯", "G", "G♯", "A", "A♯", "B"];
  var FLAT = ["C", "D♭", "D", "E♭", "E", "F", "G♭", "G", "A♭", "A", "B♭", "B"];
  var OPEN = [40, 45, 50, 55, 59, 64];
  function qualityById(id) {
    var i;
    for (i = 0; i < DATA.qualities.length; i++) if (DATA.qualities[i].id === id) return DATA.qualities[i];
    return DATA.qualities[0];
  }
  function spellPc(pc, degree, mode) {
    if (degree && degree.charAt(0) === "#") return SHARP[pc];
    if (degree && degree.charAt(0) === "b") return FLAT[pc];
    if (mode === "flat") return FLAT[pc];
    return SHARP[pc];
  }
  function fill(template, key, qual) {
    return template.replace(/\\{(\\w+)\\}/g, function (_, token) {
      if (token === "key") return key.keyName;
      if (token === "root") return key.chordName;
      var interval = Number(token);
      var pc = (key.chordPc + interval) % 12;
      return spellPc(pc, qual.degrees[String(interval)], qual.spell);
    });
  }
  function keyById(id, qualityId) {
    var found = KEYS[0];
    var i;
    for (i = 0; i < KEYS.length; i++) if (KEYS[i].id === id) found = KEYS[i];
    var qual = qualityById(qualityId);
    var chordPc = (found.pc + qual.root) % 12;
    var chordName = spellPc(chordPc, "R", qual.spell);
    var suffix = qual.suffixBass == null ? qual.suffix : "/" + spellPc((chordPc + qual.suffixBass) % 12, qual.degrees[String(qual.suffixBass)] || "R", qual.spell);
    var tones = qual.intervals.map(function (interval) {
      return spellPc((chordPc + interval) % 12, qual.degrees[String(interval)], qual.spell);
    });
    return {
      id: found.id,
      keyName: found.name,
      name: chordName,
      pc: found.pc,
      quality: qual.id,
      chordRoot: qual.root,
      chordPc: chordPc,
      chordName: chordName,
      suffix: suffix,
      tones: tones,
      toneLabels: qual.labels.slice(),
      colorFrom: qual.colorFrom,
      summary: "",
      highNote: qual.highNote,
      bassLabels: qual.bassLabels,
      walkLabel: qual.walkLabel,
      compares: qual.compares,
      degreeMap: qual.degrees,
      spellMode: qual.spell,
      piano: qual.piano,
      pianoBass: qual.pianoBass,
      bass: qual.bass
    };
  }
  function finish(key) {
    var qual = qualityById(key.quality);
    key.summary = fill(qual.summary, key, qual);
    return key;
  }
  function shapesFor(qualityId) {
    return qualityById(qualityId).shapes;
  }
  function spell(midi, key) {
    var pc = ((midi % 12) + 12) % 12;
    var interval = (pc - key.chordPc + 12) % 12;
    var degree = key.degreeMap[String(interval)];
    return spellPc(pc, degree, key.spellMode) + (Math.floor(midi / 12) - 1);
  }
  function placeShape(shape, key) {
    var shift = key.pc;
    var frets = shape.frets.map(function (fret) { return fret == null ? null : fret + shift; });
    function sounding() { return frets.filter(function (fret) { return fret != null; }); }
    while (Math.min.apply(null, sounding()) >= 13) {
      frets = frets.map(function (fret) { return fret == null ? null : fret - 12; });
    }
    while (sounding().some(function (fret) { return fret < 1; })) {
      frets = frets.map(function (fret) { return fret == null ? null : fret + 12; });
    }
    return {
      frets: frets,
      fingers: shape.fingers.slice(),
      midis: frets.map(function (fret, i) { return fret == null ? null : OPEN[i] + fret; }),
      notation: frets.map(function (fret) { return fret == null ? "x" : String(fret); }).join("-"),
      root: shape.root == null ? qualityById(key.quality).root : shape.root,
      degrees: shape.degrees || qualityById(key.quality).degrees
    };
  }
  function stringsOf(placed, key) {
    var names = ["低音 E", "A", "D", "G", "B", "高音 e"];
    var rootPc = (key.pc + placed.root) % 12;
    return placed.frets.map(function (fret, i) {
      if (fret == null) return { index: i, muted: true, fret: null, midi: null, degree: null, role: null, name: null, stringName: names[i] };
      var midi = placed.midis[i];
      var interval = ((midi % 12) - rootPc + 12) % 12;
      var degree = placed.degrees[String(interval)] || null;
      return { index: i, muted: false, fret: fret, midi: midi, degree: degree, role: degree, name: spell(midi, key), stringName: names[i] };
    });
  }
  function midiFor(key, interval, octaveBase) {
    return octaveBase + key.chordPc + interval;
  }
  function pianoNotes(key) {
    var notes = [];
    if (key.pianoBass != null) notes.push({ midi: midiFor(key, key.pianoBass, 36), role: "bass", hand: "left" });
    key.piano.forEach(function (interval, index) {
      notes.push({ midi: midiFor(key, interval, 48), role: index === 0 ? "root" : "color", hand: index === 0 && key.pianoBass == null ? "left" : "right" });
    });
    return notes;
  }
  function bassNotes(key) {
    var low = 36 + key.chordPc;
    return [
      { midi: low + key.bass[0], role: "root" },
      { midi: low + key.bass[1], role: "fifth" },
      { midi: low + 12, role: "root" }
    ];
  }
  var wrapped = {
    KEYS: KEYS,
    QUALITIES: DATA.qualities.map(function (item) { return { id: item.id, label: item.label }; }),
    keyById: function (id, qualityId) { return finish(keyById(id, qualityId)); },
    shapesFor: shapesFor,
    placeShape: placeShape,
    stringsOf: stringsOf,
    spell: spell,
    pianoNotes: pianoNotes,
    bassNotes: bassNotes
  };
  return wrapped;
});
`;
}

function verifySource() {
  return `var theory = require("./theory.js");
var sound = require("../../assets/sound.js");
var failed = 0;
function assert(cond, message) {
  if (!cond) { failed += 1; console.error("FAIL: " + message); }
}
theory.QUALITIES.forEach(function (item) {
  theory.KEYS.forEach(function (raw) {
    var key = theory.keyById(raw.id, item.id);
    theory.shapesFor(item.id).forEach(function (shape) {
      var placed = theory.placeShape(shape, key);
      var degrees = [];
      theory.stringsOf(placed, key).forEach(function (string, index) {
        if (string.muted) {
          assert(string.degree == null && placed.midis[index] == null, shape.id + " mute labeled");
          return;
        }
        assert(string.fret >= 1 && string.fret <= 15, shape.id + " " + raw.name + " fret " + string.fret + " " + placed.notation);
        assert(placed.midis[index] === [40, 45, 50, 55, 59, 64][index] + string.fret, "midi");
        assert(string.degree, shape.id + " " + raw.name + " foreign " + placed.notation);
        degrees.push(string.degree);
      });
      (shape.need || []).forEach(function (degree) {
        assert(degrees.indexOf(degree) >= 0, shape.id + " " + raw.name + " missing " + degree + " in " + degrees.join(","));
      });
      if (!shape.allowNoRoot) assert(degrees.indexOf("R") >= 0, shape.id + " missing root");
    });
    var piano = theory.pianoNotes(key);
    piano.forEach(function (note, index) {
      assert(index === 0 || note.midi !== piano[index - 1].midi, "piano duplicate");
    });
  });
  var c = theory.keyById("C", item.id);
  theory.shapesFor(item.id).forEach(function (shape) {
    var placed = theory.placeShape(shape, c);
    var base = shape.frets.map(function (fret) { return fret == null ? "x" : String(fret); }).join("-");
    if (Math.min.apply(null, shape.frets.filter(function (fret) { return fret != null; })) < 13) {
      assert(placed.notation === base, shape.id + " C notation " + placed.notation + " != " + base);
    }
  });
});
var tone = sound.renderPiano(60, 22050, 0.4);
assert(tone.length > 1000 && tone[100] === tone[100], "piano renders");
if (failed) { console.error(failed + " failed"); process.exit(1); }
console.log("all checks passed");
`;
}

function esc(text) { return String(text); }

function changesHtml(changes) {
  return changes.map((change) => `<div class="change">
            <p class="where">${esc(change[0])}</p>
            <p class="notation">${esc(change[1])}</p>
            <button type="button" class="btn" data-chords="${esc(change[2])}">听这段</button>
          </div>`).join("\n");
}

function songsHtml(lesson) {
  const cards = (lesson.songs || []).map((item) => `<article class="song ${item.group}">
        <h3>${esc(item.title)}</h3>
        <p class="meta">${esc(item.meta)}</p>
        ${item.caveat ? `<p class="caveat">${esc(item.caveat)}</p>` : ""}
        ${item.beats.map((beat) => `<p class="beat"><span class="label">${esc(beat[0])}</span>${esc(beat[1])}</p>`).join("\n")}
        <div class="changes">
          ${changesHtml(item.changes)}
        </div>
        ${item.source ? `<p class="source">${esc(item.source)}</p>` : ""}
      </article>`).join("\n");
  const groupHeads = [];
  let html = "";
  let last = "";
  (lesson.songs || []).forEach((item, index) => {
    if (item.group !== last) {
      html += `<h3 class="group-title${item.group === "jazz" ? " jazz" : ""}">${item.group === "jazz" ? "爵士 / 功能" : "流行"}</h3>\n`;
      last = item.group;
    }
    html += cards.split("</article>")[index] ? "" : "";
  });
  // rebuild simply
  html = "";
  last = "";
  for (const item of lesson.songs || []) {
    if (item.group !== last) {
      html += `<h3 class="group-title${item.group === "jazz" ? " jazz" : ""}">${item.group === "jazz" ? "爵士 / 功能" : "流行"}</h3>\n`;
      last = item.group;
    }
    html += `<article class="song ${item.group}">
        <h3>${item.title}</h3>
        <p class="meta">${item.meta}</p>
        ${item.caveat ? `<p class="caveat">${item.caveat}</p>` : ""}
        ${item.beats.map((beat) => `<p class="beat"><span class="label">${beat[0]}</span>${beat[1]}</p>`).join("\n")}
        <div class="changes">${changesHtml(item.changes)}</div>
        ${item.source ? `<p class="source">${item.source}</p>` : ""}
      </article>\n`;
  }
  return html;
}

